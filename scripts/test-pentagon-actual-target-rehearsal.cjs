'use strict';
const assert=require('node:assert/strict'),crypto=require('node:crypto');
const m=require('./pentagon-actual-target-rehearsal.cjs');let count=0;
const test=(name,fn)=>{fn();count++;};
const t={name:'check_results',columns:[{name:'id',type:'bigint',nullable:false},{name:'checked_at',type:'timestamp with time zone',nullable:false},{name:'result',type:'json',nullable:true}],pk:['id']};
test('source loopback',()=>assert.equal(m.config(m.SOURCE_DB).host,'127.0.0.1'));
test('target fixed port',()=>assert.equal(m.config(m.TARGET_DB).port,55432));
test('source and target differ',()=>assert.notEqual(m.SOURCE_DB,m.TARGET_DB));
test('production db refused',()=>assert.throws(()=>m.config('postgres'),/DATABASE_NOT_ALLOWLISTED/));
test('Tradevice db refused',()=>assert.throws(()=>m.config('scqzlcivherovlwqypeu'),/DATABASE_NOT_ALLOWLISTED/));
test('connection URL refused',()=>assert.throws(()=>m.config('postgresql://invalid'),/DATABASE_NOT_ALLOWLISTED/));
test('empty database refused',()=>assert.throws(()=>m.config(''),/DATABASE_NOT_ALLOWLISTED/));
test('no production password',()=>assert.equal(m.config(m.TARGET_DB).password,''));
test('SQL identifier quoting',()=>assert.equal(m.qi('a"b'),'"a""b"'));
test('typed table private',()=>assert.ok(m.createTableSql(t).startsWith('CREATE TABLE "'+m.STAGE+'".')));
test('no public inserts',()=>assert.ok(!/INSERT INTO\s+public\./i.test(m.insertSql(t))));
test('no overwrite on conflict',()=>assert.ok(m.insertSql(t).endsWith('DO NOTHING')));
test('no auto serial sequence',()=>assert.ok(!/serial|nextval/i.test(m.createTableSql(t))));
test('timestamp preserved',()=>assert.ok(m.createTableSql(t).includes('timestamp with time zone')));
test('json not converted to jsonb',()=>assert.ok(m.createTableSql(t).includes('"result" json')));
test('text wire avoids JS number coercion',()=>assert.ok(m.insertSql(t).includes('"id" text')));
test('payload parameterized',()=>assert.ok(m.insertSql(t).includes('$1::json')));
test('source selection explicitly public',()=>assert.ok(m.selectSql(t).includes('FROM public."check_results"')));
test('stage selection explicitly private',()=>assert.ok(m.selectSql(t,m.STAGE).includes('FROM "'+m.STAGE+'"."legacy_check_results"')));
test('batch limit parameterized',()=>assert.ok(m.selectSql(t,'public',true).includes('LIMIT $1 OFFSET $2')));
test('table injection refused',()=>assert.throws(()=>m.stageTable('domains; DROP SCHEMA public'),/UNSAFE_TABLE_NAME/));
test('unreviewed type refused',()=>assert.throws(()=>m.typeSql('text); DROP TABLE domains;--'),/UNREVIEWED_COLUMN_TYPE/));
test('schema type rejected',()=>assert.throws(()=>m.typeSql('public.custom_type'),/UNREVIEWED_COLUMN_TYPE/));
test('bytea explicitly supported',()=>assert.equal(m.typeSql('bytea'),'bytea'));
test('numeric scale supported',()=>assert.equal(m.typeSql('numeric(14,0)'),'numeric(14,0)'));
test('missing pk refused',()=>assert.throws(()=>m.createTableSql({...t,pk:[]}),/MISSING_COLUMNS_OR_PRIMARY_KEY/));
test('no target candidate never assigned',()=>assert.equal(m.domainState(0,1),'NEW_REQUIRES_REVIEW'));
test('same tenant two fleets ambiguous',()=>assert.equal(m.domainState(1,2),'AMBIGUOUS_FLEET'));
test('multiple target candidates ambiguous',()=>assert.equal(m.domainState(2,1),'AMBIGUOUS_FLEET'));
test('single candidate still needs review',()=>assert.equal(m.domainState(1,1),'IDENTITY_REVIEW_REQUIRED'));
test('hash framing distinguishes row boundaries',()=>{const h=rows=>m.addRows(crypto.createHash('sha256'),rows.map(encoded=>({encoded}))).digest('hex');assert.notEqual(h(['ab','c']),h(['a','bc']));});
test('hash deterministic',()=>{const h=()=>m.addRows(crypto.createHash('sha256'),[{encoded:'9007199254740993'}]).digest('hex');assert.equal(h(),h());});
console.log('PENTAGON_ACTUAL_TARGET_UNIT_TESTS_PASS='+count);
